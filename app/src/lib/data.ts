const STOP_BY_ID = new Map(BASE_STOPS.map((s) => [s.id, s]));

function buildStopPoints(entries: Array<[string, number, number]>): RouteStopPoint[] {
  return entries
    .map(([stopId, typicalTimeMins, fareFromStart], index) => {
      const stop = STOP_BY_ID.get(stopId);
      if (!stop) return null;
      return {
        stopId: stop.id,
        name: stop.name,
        bengaliName: stop.bengaliName,
        lat: stop.lat,
        lng: stop.lng,
        sequence: index + 1,
        typicalTimeMins,
        fareFromStart,
      };
    })
    .filter((x): x is NonNullable<typeof x> => x !== null);
}

