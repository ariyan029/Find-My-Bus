export const KOLKATA_ROUTES: BusRoute[] = ROUTE_SPECS.map((spec) => {
  const stopPoints = buildStopPoints(spec.stops);
  const lastPoint = stopPoints[stopPoints.length - 1];
  const firstPoint = stopPoints[0];
  return {
    id: spec.id,
    routeNumber: spec.routeNumber,
    name: spec.name,
    source: firstPoint?.name ?? "",
    destination: lastPoint?.name ?? "",
    distanceKm: spec.distanceKm,
    totalStops: stopPoints.length,
    busType: spec.busType,
    operator: spec.operator,
    avgTripMins: lastPoint?.typicalTimeMins ?? 45,
    fareMin: stopPoints[1]?.fareFromStart ?? 10,
    fareMax: lastPoint?.fareFromStart ?? 25,
    frequencyMins: spec.frequencyMins,
    peakFrequencyMins: spec.peakFrequencyMins ?? spec.frequencyMins,
    firstBusTime: spec.firstBusTime ?? "05:30",
    lastBusTime: spec.lastBusTime ?? "22:15",
    stops: stopPoints.map((s) => s.name),
    stopPoints,
  };
});

export const KOLKATA_STOPS: BusStop[] = BASE_STOPS.map((stop) => {
  const connectingRoutes = KOLKATA_ROUTES.filter((r) =>
    r.stopPoints?.some((sp) => sp.stopId === stop.id)
  ).map((r) => r.routeNumber);
  return {
    ...stop,
    connectingRoutes,
  };
});

